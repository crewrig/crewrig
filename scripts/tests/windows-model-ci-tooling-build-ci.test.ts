// windows-model-ci-tooling-build-ci.test.ts — the cross-system proof of build-ci.ts (spec 0262
// R23). Generation, `--check` and drift detection run against the real repository from PowerShell
// on Windows; off Windows they run from the default shell so the file also passes in Linux CI.
// Fixtures are built at runtime inside one mkdtemp directory, which is the only path removed.
// Interpreters are resolved from the PARENT PATH before the child PATH is narrowed. The
// `windows-model-ci-tooling` job runs every `windows-model-ci-tooling-*.test.ts` file.

import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { describe, it } from "node:test";
import { fileURLToPath } from "node:url";

import { defaultIsFile } from "../lib/worktree-claim/launch-windows.ts";
import { expectStatus, resolveInterpreters, spawnEntry, why } from "./lib/windows-proof-support.ts";
import type { Run } from "./lib/windows-proof-support.ts";

const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
const script = path.join(repo, "scripts", "build-ci.ts");
const committed = fs.readFileSync(path.join(repo, ".gitlab-ci.yml"));
const reference = fs.readFileSync(path.join(repo, "ci", "ci-capabilities.yml"));

/** A scratch root holding `bin/` and `work/` (a repo-shaped dir with ci/ and the given output). */
function withBox<T>(
  output: Buffer | null,
  body: (root: string, work: string, bin: string) => T,
): T {
  const root = fs.realpathSync.native(
    fs.mkdtempSync(path.join(os.tmpdir(), "windows-model-ci-tooling-")),
  );
  try {
    const bin = path.join(root, "bin");
    const work = path.join(root, "work");
    fs.mkdirSync(bin);
    fs.mkdirSync(path.join(work, "ci"), { recursive: true });
    fs.writeFileSync(path.join(work, "ci", "ci-capabilities.yml"), reference);
    // build-ci reads the Task pin at generation (spec 0282); a root without one fails closed.
    fs.copyFileSync(path.join(repo, "ci", "task-pin.json"), path.join(work, "ci", "task-pin.json"));
    if (output !== null) fs.writeFileSync(path.join(work, ".gitlab-ci.yml"), output);
    return body(root, work, bin);
  } finally {
    fs.rmSync(root, { recursive: true, force: true });
  }
}

function run(entry: string, work: string, root: string, bin: string, args: string[]): Run {
  // Resolved from the parent environment, before spawnEntry narrows the child PATH.
  const interpreters = resolveInterpreters({
    platform: process.platform,
    env: process.env,
    isFile: defaultIsFile,
  });
  console.log(`windows-model-ci-tooling-build-ci: ${entry}: ${interpreters.notes.join("; ")}`);
  return spawnEntry({
    entry,
    script,
    args,
    shell: "pwsh",
    env: {
      GIT_CONFIG_NOSYSTEM: "1",
      NODE_OPTIONS: "--disable-warning=MODULE_TYPELESS_PACKAGE_JSON",
      REPO_DIR: work,
    },
    home: root,
    bin,
    cwd: root,
    interpreters,
  });
}

const hasCr = (b: Buffer): boolean => b.includes(0x0d);

describe("windows model-ci-tooling: build-ci", () => {
  it("generates a .gitlab-ci.yml byte-identical to the committed one, with LF only", () => {
    withBox(Buffer.from("stale\n"), (root, work, bin) => {
      const r = run("build-ci generate", work, root, bin, []);
      expectStatus(r, 0);
      assert.equal(r.err, "", why(r, "nothing on stderr"));
      const generated = fs.readFileSync(path.join(work, ".gitlab-ci.yml"));
      assert.ok(!hasCr(generated), why(r, "generated file has no carriage return"));
      assert.ok(!hasCr(committed), "the committed .gitlab-ci.yml must be LF-only");
      assert.ok(generated.equals(committed), why(r, "generated bytes equal the committed bytes"));
    });
  });

  it("--check on the committed file exits 0 and reports OK", () => {
    withBox(committed, (root, work, bin) => {
      const r = run("build-ci --check", work, root, bin, ["--check"]);
      expectStatus(r, 0);
      assert.equal(
        r.out.replaceAll("\r\n", "\n"),
        "OK: .gitlab-ci.yml matches the CI capability reference.\n",
        why(r, "OK line"),
      );
      assert.equal(r.err, "", why(r, "nothing on stderr"));
    });
  });

  it("--check on a drifted copy exits 1 with the DRIFT line first", () => {
    const lines = committed.toString("utf8").split("\n");
    const at = lines.findIndex((l) => l.startsWith("  image:"));
    assert.ok(at >= 0, "an image line to drift");
    lines[at] = `${lines[at]}-drifted`;
    withBox(Buffer.from(lines.join("\n")), (root, work, bin) => {
      const r = run("build-ci --check drift", work, root, bin, ["--check"]);
      expectStatus(r, 1);
      const err = r.err.replaceAll("\r\n", "\n");
      assert.ok(
        err.startsWith(
          `DRIFT: ${path.join(work, ".gitlab-ci.yml")} differs from a fresh derivation of ci/ci-capabilities.yml\n`,
        ),
        why(r, "DRIFT first line"),
      );
      assert.match(err, /-drifted/, why(r, "the drifted line appears in the diff"));
      assert.match(
        err,
        /FAILED: run 'node --disable-warning=MODULE_TYPELESS_PACKAGE_JSON scripts\/build-ci\.ts' to regenerate/,
        why(r, "tail"),
      );
      assert.equal(r.out, "", why(r, "nothing on stdout"));
    });
  });

  it("--check without a committed file reports DRIFT and exits 1", () => {
    withBox(null, (root, work, bin) => {
      const r = run("build-ci --check missing", work, root, bin, ["--check"]);
      expectStatus(r, 1);
      assert.ok(r.err.startsWith("DRIFT: "), why(r, "DRIFT first line"));
    });
  });

  it("ignores an unknown argument exactly as the shell does (no usage text)", () => {
    withBox(committed, (root, work, bin) => {
      const r = run("build-ci --bogus", work, root, bin, ["--bogus", "--check"]);
      expectStatus(r, 0);
      assert.equal(r.err, "", why(r, "no usage diagnostic on stderr"));
      assert.match(r.out, /^OK: /, why(r, "the check still ran"));
    });
  });
});
