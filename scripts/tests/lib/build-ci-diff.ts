// build-ci-diff.ts — shared harness of the build-ci differential tests: runs the shell
// and the TypeScript entry in scratch trees and compares every observable.

import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { after } from "node:test";

import { REPO, WINDOWS } from "./worktree-fixtures.ts";

export const SH = path.join(REPO, "scripts", "build-ci.sh");
export const TS = path.join(REPO, "scripts", "build-ci.ts");
export const REAL_REF = fs.readFileSync(path.join(REPO, "ci", "ci-capabilities.yml"), "utf8");
const HAS_YQ = !WINDOWS && spawnSync("yq", ["--version"], { stdio: "ignore" }).status === 0;
export const SKIP = HAS_YQ ? false : "SKIP: shell leg needs bash and yq (not on win32)";
export const roots: string[] = [];
after(() => {
  for (const root of roots) fs.rmSync(root, { recursive: true, force: true });
});

interface Run {
  stdout: string;
  stderr: string;
  status: number | null;
  generated: string | null;
}

/** A scratch repo root holding `ci/ci-capabilities.yml` (and a committed output if given). */
function tree(reference: string, committed?: string): string {
  const root = fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(), "crewrig-bci-")));
  roots.push(root);
  fs.mkdirSync(path.join(root, "ci"));
  fs.writeFileSync(path.join(root, "ci", "ci-capabilities.yml"), reference);
  if (committed !== undefined) fs.writeFileSync(path.join(root, ".gitlab-ci.yml"), committed);
  return root;
}

/** Run one entry in a fresh tree; paths in the output are normalised to `<ROOT>`. */
export function run(
  entry: "sh" | "ts",
  args: string[],
  reference: string,
  committed?: string,
): Run {
  const root = tree(reference, committed);
  const [cmd, argv] =
    entry === "sh"
      ? ["bash", [SH, ...args]]
      : [process.execPath, ["--disable-warning=MODULE_TYPELESS_PACKAGE_JSON", TS, ...args]];
  const r = spawnSync(cmd, argv, {
    encoding: "utf8",
    env: { ...process.env, LC_ALL: "C", REPO_DIR: root },
  });
  const norm = (s: string): string => s.replaceAll(root, "<ROOT>");
  const out = path.join(root, ".gitlab-ci.yml");
  return {
    stdout: norm(r.stdout),
    stderr: norm(r.stderr),
    status: r.status,
    generated: fs.existsSync(out) ? fs.readFileSync(out, "utf8") : null,
  };
}

export function same(args: string[], reference: string, committed?: string): void {
  const sh = run("sh", args, reference, committed);
  const ts = run("ts", args, reference, committed);
  assert.equal(ts.status, sh.status, `status\n${ts.stderr}`);
  assert.equal(ts.stderr, sh.stderr, "stderr");
  assert.equal(ts.stdout, sh.stdout, "stdout");
  assert.equal(ts.generated, sh.generated, "generated bytes");
}
