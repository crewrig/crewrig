// Per-file limit on the hand-authored CI files (spec 0309 R1, R5). It replaces the global line cap:
// 0285 R1 (the 8,880-line total and its ratchet and report), 0285 R2 (the comment-line count of the
// reference) and 0287 R13 (the line ratchet, floor and hard cap, as amended by its delta-01).
// Hand-authored files: build.yml, every `_ci-*.yml` and every file of ci/capabilities/. Generated
// files are excluded by their marker, never by name; `.gitlab-ci.yml` is generated, so it fails
// when the marker is absent. LIMIT: the largest file after the split is ci/capabilities/
// integration.yml at 424 lines; 424 x 1.10 = 466.4, rounded up to the next multiple of 50 is 500.
// Raising it is a deliberate edit of this constant, with the reason in the pull request body.

import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import { describe, it } from "node:test";
import { fileURLToPath } from "node:url";

export const LIMIT = 500;
export const MARKER = "GENERATED by scripts/build-ci.ts";
const GENERATED_PATH = ".gitlab-ci.yml";

export interface CiFile {
  path: string;
  text: string;
}

const lineCount = (text: string): number => {
  const lines = text.split("\n");
  return lines[lines.length - 1] === "" ? lines.length - 1 : lines.length;
};

/** One problem line per offending file, naming it; empty when every file is within the limit. */
export function findProblems(files: CiFile[], limit: number = LIMIT): string[] {
  const problems: string[] = [];
  for (const f of files) {
    if (f.text.split("\n", 5).some((l) => l.includes(MARKER))) continue;
    if (f.path === GENERATED_PATH) {
      problems.push(`${f.path}: generated file without the marker "${MARKER}"`);
      continue;
    }
    const n = lineCount(f.text);
    if (n > limit) problems.push(`${f.path}: ${n} lines, limit ${limit}`);
  }
  return problems;
}

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");

function realFiles(): CiFile[] {
  const rel: string[] = [".github/workflows/build.yml", GENERATED_PATH];
  for (const n of fs.readdirSync(path.join(repoRoot, ".github/workflows")).sort()) {
    if (/^_ci-.*\.yml$/.test(n)) rel.push(`.github/workflows/${n}`);
  }
  for (const n of fs.readdirSync(path.join(repoRoot, "ci/capabilities")).sort()) {
    rel.push(`ci/capabilities/${n}`);
  }
  return rel.map((p) => ({ path: p, text: fs.readFileSync(path.join(repoRoot, p), "utf8") }));
}

const lines = (n: number): string => "x\n".repeat(n);

describe("ci-file-limit fixtures", () => {
  it("a file at the limit passes", () => {
    assert.deepEqual(findProblems([{ path: "ci/capabilities/a.yml", text: lines(LIMIT) }]), []);
  });

  it("a file over the limit fails, naming the file and its count", () => {
    const p = findProblems([{ path: "ci/capabilities/b.yml", text: lines(LIMIT + 1) }]);
    assert.equal(p.length, 1);
    assert.match(p[0] as string, /ci\/capabilities\/b\.yml: 501 lines/);
  });

  it("a generated file over the limit is excluded by its marker", () => {
    const text = `# .gitlab-ci.yml - ${MARKER}\n${lines(LIMIT + 50)}`;
    assert.deepEqual(findProblems([{ path: GENERATED_PATH, text }]), []);
  });

  it("an unmarked .gitlab-ci.yml fails whatever its size", () => {
    const p = findProblems([{ path: GENERATED_PATH, text: "stages: []\n" }]);
    assert.equal(p.length, 1);
    assert.match(p[0] as string, /\.gitlab-ci\.yml: generated file without the marker/);
  });
});

describe("ci-file-limit real tree", () => {
  it(`every hand-authored CI file has at most ${LIMIT} lines`, () => {
    const files = realFiles();
    assert.ok(files.length > 15, "the CI files were found");
    assert.deepEqual(findProblems(files), []);
  });
});
