#!/usr/bin/env node
// build-usage-validator.js — generate the ajv-precompiled STANDALONE usage-
// record validator committed under scripts/lib/usage-store/validator/ (spec
// 0207 PLAN v3 step 2), so the record of truth's own write path (journal.js)
// never depends on `npm install` at runtime — only at generation time, here.
//
// This is the repository's first vendored third-party source. Every copied
// file (ajv-formats-formats.js, ucs2length.js) gets an MIT-notice header
// naming its upstream package, version and source path; LICENSE-ajv and
// LICENSE-ajv-formats are copied byte-verbatim from the installed packages.
//
// Generator options, matching scripts/lib/usage-record-validator.js's own
// strict/strictRequired/allErrors choice (l. 65) for the same reason stated
// there (the schema's allOf/if/then blocks declare `required` once, not
// per-branch, which ajv's strictRequired would otherwise flag): strict:true,
// strictRequired:false, allErrors:true, code:{source:true, esm:false,
// formats: a reference to our own committed formats.js shim rather than
// ajv-formats' own dist/formats.js} — the one option that keeps the emitted
// shim to a single external formats entry point instead of two (one for the
// date-time keyword via ajv-formats/dist/formats, a second, unavoidable
// either way, for ucs2length via ajv/dist/runtime).
//
// Usage:
//   node scripts/build-usage-validator.js           regenerate and write
//   node scripts/build-usage-validator.js --check    diff-only, exit 1 on drift
//
// Exit codes: 0 clean (or written), 1 drift (--check only), 2 preflight fault
// (ajv/ajv-formats not installed).

'use strict';

const fs = require('fs');
const os = require('os');
const path = require('path');

const REPO_DIR = path.join(__dirname, '..');
const SCHEMA_PATH = path.join(REPO_DIR, 'schemas', 'usage-record', 'v1.schema.json');
const OUT_DIR = path.join(REPO_DIR, 'scripts', 'lib', 'usage-store', 'validator');

const CHECK_MODE = process.argv.includes('--check');

function fail(reason, detail) {
  console.error(`FATAL: ${reason}${detail ? ` — ${detail}` : ''}`);
  process.exit(CHECK_MODE ? 1 : 2);
}

let Ajv2020;
let standaloneCode;
let addFormats;
let ajvPkg;
let ajvFormatsPkg;
let _;
try {
  Ajv2020 = require('ajv/dist/2020');
  standaloneCode = require('ajv/dist/standalone');
  addFormats = require('ajv-formats');
  ({ _ } = require('ajv/dist/compile/codegen'));
  ajvPkg = require('ajv/package.json');
  ajvFormatsPkg = require('ajv-formats/package.json');
} catch (err) {
  if (err.code === 'MODULE_NOT_FOUND') {
    fail('ajv not installed', 'run `npm install` first');
  }
  throw err;
}

function mitNoticeHeader(pkgName, version, sourcePath) {
  return (
    `// Vendored verbatim from ${pkgName}@${version} (${sourcePath}), MIT\n` +
    `// licensed — see LICENSE-${pkgName}. Generated by\n` +
    `// scripts/build-usage-validator.js; do not hand-edit.\n`
  );
}

function generate() {
  const schema = JSON.parse(fs.readFileSync(SCHEMA_PATH, 'utf8'));

  const ajv = new Ajv2020({
    strict: true,
    strictRequired: false,
    allErrors: true,
    code: { source: true, esm: false, formats: _`require("./formats.js")` },
  });
  addFormats(ajv, { mode: 'full' });
  const validate = ajv.compile(schema);
  let validateCode = standaloneCode(ajv, validate);

  // The one residual external reference ajv's own runtime emits regardless
  // of the code.formats option — rewritten to the committed local copy so
  // the resolution path never touches node_modules.
  const UCS2_UPSTREAM = 'require("ajv/dist/runtime/ucs2length")';
  const UCS2_LOCAL = 'require("./ucs2length.js")';
  if (!validateCode.includes(UCS2_UPSTREAM)) {
    fail('generated output did not contain the expected ucs2length require — ajv codegen shape has changed');
  }
  validateCode = validateCode.split(UCS2_UPSTREAM).join(UCS2_LOCAL);

  const generatorNotice =
    `// validate.js — ajv-precompiled standalone validator for\n` +
    `// schemas/usage-record/v1.schema.json (spec 0205), generated by\n` +
    `// scripts/build-usage-validator.js. Do not hand-edit; re-run the\n` +
    `// generator instead. Loads and runs with no node_modules on the\n` +
    `// resolution path.\n` +
    `// generator: ajv@${ajvPkg.version} ajv-formats@${ajvFormatsPkg.version}\n`;

  const formatsUpstream = fs.readFileSync(
    path.join(REPO_DIR, 'node_modules', 'ajv-formats', 'dist', 'formats.js'),
    'utf8'
  );
  const ucs2lengthUpstream = fs.readFileSync(
    path.join(REPO_DIR, 'node_modules', 'ajv', 'dist', 'runtime', 'ucs2length.js'),
    'utf8'
  );
  const ajvLicense = fs.readFileSync(path.join(REPO_DIR, 'node_modules', 'ajv', 'LICENSE'), 'utf8');
  const ajvFormatsLicense = fs.readFileSync(
    path.join(REPO_DIR, 'node_modules', 'ajv-formats', 'LICENSE'),
    'utf8'
  );

  const formatsShim = `'use strict';\nmodule.exports = require('./ajv-formats-formats.js').fullFormats;\n`;

  return {
    'validate.js': `${generatorNotice}${validateCode}`,
    'formats.js': formatsShim,
    'ajv-formats-formats.js':
      mitNoticeHeader('ajv-formats', ajvFormatsPkg.version, 'dist/formats.js') + formatsUpstream,
    'ucs2length.js':
      mitNoticeHeader('ajv', ajvPkg.version, 'dist/runtime/ucs2length.js') + ucs2lengthUpstream,
    'LICENSE-ajv': ajvLicense,
    'LICENSE-ajv-formats': ajvFormatsLicense,
  };
}

function main() {
  const files = generate();

  if (CHECK_MODE) {
    const drifted = [];
    for (const [name, content] of Object.entries(files)) {
      const committedPath = path.join(OUT_DIR, name);
      let committed;
      try {
        committed = fs.readFileSync(committedPath, 'utf8');
      } catch (err) {
        drifted.push(`${name}: missing — generated output drift`);
        continue;
      }
      if (committed !== content) {
        if (name === 'validate.js') {
          const committedGenLine = committed.split('\n').find((l) => l.startsWith('// generator: '));
          const freshGenLine = content.split('\n').find((l) => l.startsWith('// generator: '));
          if (committedGenLine !== freshGenLine) {
            drifted.push(`${name}: generator version drift (committed "${committedGenLine}", installed "${freshGenLine}")`);
            continue;
          }
        }
        drifted.push(`${name}: generated output drift`);
      }
    }
    if (drifted.length > 0) {
      console.error('FATAL: scripts/lib/usage-store/validator/ is out of date:');
      for (const d of drifted) {
        console.error(`  - ${d}`);
      }
      console.error('Regenerate with: node scripts/build-usage-validator.js');
      process.exit(1);
    }
    console.log('OK: scripts/lib/usage-store/validator/ matches the generator output.');
    process.exit(0);
  }

  fs.mkdirSync(OUT_DIR, { recursive: true });
  for (const [name, content] of Object.entries(files)) {
    fs.writeFileSync(path.join(OUT_DIR, name), content);
  }
  console.log(`Wrote ${Object.keys(files).length} file(s) to ${path.relative(REPO_DIR, OUT_DIR)}/`);
}

main();
